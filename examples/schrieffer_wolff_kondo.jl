# # Schrieffer–Wolff transformation of the Anderson model

# `linsolve` from KrylovKit works on symbolic kets, so second-order perturbation theory can be done exactly in a
# space far too large for matrices. We compute the effective Hamiltonian of an Anderson impurity coupled to 81 bath
# levels on its four-dimensional low-energy subspace and recover the Kondo exchange ``J\,\mathbf{S}\cdot\mathbf{s}``
# of Schrieffer and Wolff[^1][^2].

# ## Second-order effective Hamiltonian

# Let ``P`` project onto a degenerate low-energy subspace of ``H_0`` with energy ``E_0``, and let ``V`` couple it only
# to states outside. To second order in ``V`` the dynamics within the subspace is generated by
# ``H_\mathrm{eff} = P V (E_0 - H_0)^{-1} V P``.
#
# For the Anderson model, the low-energy states have one electron on the impurity, one at the Fermi level and all
# levels below filled. Schrieffer and Wolff found that ``H_\mathrm{eff}`` is, up to a constant, the exchange
# ``J\,\mathbf{S}\cdot\mathbf{s}`` between the impurity spin and the spin at the Fermi level, with
# ``J = 2V^2 \left(1/|\varepsilon_d| + 1/(\varepsilon_d + U)\right)``.

# ## An impurity with 81 bath levels

# The full space has dimension ``2^{2N + 2}``, and the effective Hamiltonian is a ``4 × 4`` matrix.
using FermionicHilbertSpaces, KrylovKit, LinearAlgebra

@fermions d c
N = 81
εd, U, V = -1.0, 3.0, 0.05
εk = range(-1, 1, length = N)
kF = (N + 1) ÷ 2
spins = [:↑, :↓]
H = tensor_product(hilbert_space(d, spins), hilbert_space(c, [(k, σ) for k in 1:N for σ in spins]))
H0 = sum(εd * d[σ]' * d[σ] for σ in spins) + U * d[:↑]' * d[:↑] * d[:↓]' * d[:↓] +
    sum(εk[k] * c[k, σ]' * c[k, σ] for k in 1:N for σ in spins)
Vhyb = sum(V * d[σ]' * c[k, σ] + hc for k in 1:N for σ in spins)
vacuum = Ket("0"^(2N + 2), H)
fermi_sea = prod(c[k, σ]' for k in 1:(kF - 1) for σ in spins) * vacuum
low_energy = [d[σ]' * c[kF, τ]' * fermi_sea for σ in spins for τ in spins]
E0 = εd + 2sum(εk[1:(kF - 1)])
(log2_dimension = log2(dim(H)), effective_dimension = length(low_energy))

# For each low-energy state ``p`` we solve ``(E_0 - H_0) x = V|p⟩`` and take overlaps with ``V|p'⟩``. The result is
# compared with a second-order formula, so a loose solver tolerance is enough.
xs = [linsolve(x -> E0 * x - H0 * x, Vhyb * p; rtol = 1.0e-6)[1] for p in low_energy]
Heff = [dot(Vhyb * p, x) for p in low_energy, x in xs]
λ = eigvals(Hermitian(Heff))
J = 2V^2 * (1 / abs(εd) + 1 / (εd + U))
@assert isapprox(λ[2] - λ[1], J; rtol = 1.0e-4)
@assert isapprox(Heff[2, 3], J / 2; rtol = 1.0e-4)

# Removing the constant and dividing by ``J`` leaves ``\mathbf{S}\cdot\mathbf{s}`` in the basis
# ``|{\uparrow\uparrow}⟩, |{\uparrow\downarrow}⟩, |{\downarrow\uparrow}⟩, |{\downarrow\downarrow}⟩`` of impurity and
# Fermi-level spins: the singlet lies ``J`` below the triplet.
round.(real(Heff - tr(Heff) / 4 * I) / J; digits = 3)

